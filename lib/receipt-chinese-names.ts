export function normalizeReceiptItemCode(code: string) {
  return code.trim().replace(/\s+/g, "").replace(/\.$/, "").toUpperCase();
}

export function getReceiptChineseName(code: string | null | undefined) {
  if (!code) {
    return undefined;
  }

  return receiptChineseNames[normalizeReceiptItemCode(code)];
}
